#!/usr/bin/env node

/**
 * Font Hash Script
 * For every static TTF under fonts/<dir>/, computes the sha256 of the file bytes and reads
 * head.unitsPerEm + hhea.ascender/descender/lineGap, then writes src/font-metrics.ts.
 *
 * Usage:
 *   node hash-fonts.js
 */

import { createHash } from 'crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const FONTS_DIR = join(__dirname, '..', 'fonts')
const OUT_FILE = join(__dirname, '..', 'src', 'font-metrics.ts')

/** Find a table's offset in the sfnt table directory */
function tableOffset(buf, tag) {
	const numTables = buf.readUInt16BE(4)
	for (let i = 0; i < numTables; i++) {
		const rec = 12 + i * 16
		if (buf.toString('latin1', rec, rec + 4) === tag) return buf.readUInt32BE(rec + 8)
	}
	throw new Error(`table '${tag}' not found`)
}

function readMetrics(buf) {
	const head = tableOffset(buf, 'head')
	const hhea = tableOffset(buf, 'hhea')
	return {
		sha256: createHash('sha256').update(buf).digest('hex'),
		unitsPerEm: buf.readUInt16BE(head + 18),
		ascender: buf.readInt16BE(hhea + 4),
		descender: buf.readInt16BE(hhea + 6),
		lineGap: buf.readInt16BE(hhea + 8)
	}
}

const entries = []
for (const dir of readdirSync(FONTS_DIR).sort()) {
	if (dir.startsWith('.') || !statSync(join(FONTS_DIR, dir)).isDirectory()) continue
	for (const file of readdirSync(join(FONTS_DIR, dir)).sort()) {
		if (!file.endsWith('.ttf')) continue
		const key = `${dir}/${file}`
		try {
			entries.push([key, readMetrics(readFileSync(join(FONTS_DIR, key)))])
		} catch (err) {
			console.error(`hash-fonts: ${key}: ${err.message}`)
			process.exit(1)
		}
	}
}

const body = entries
	.map(
		([key, m]) =>
			`\t'${key}': {\n\t\tsha256: '${m.sha256}',\n\t\tunitsPerEm: ${m.unitsPerEm},\n` +
			`\t\tascender: ${m.ascender},\n\t\tdescender: ${m.descender},\n\t\tlineGap: ${m.lineGap}\n\t}`
	)
	.join(',\n')

writeFileSync(
	OUT_FILE,
	`// SPDX-FileCopyrightText: Szilárd Hajba
// SPDX-License-Identifier: LGPL-3.0-or-later

// GENERATED by scripts/hash-fonts.js — do not edit by hand.

export interface FontMetrics {
	/** sha256 of the TTF bytes (hex) — the font identity */
	sha256: string
	unitsPerEm: number
	/** hhea ascender/descender/lineGap, font units */
	ascender: number
	descender: number
	lineGap: number
}

/** Keyed by '<dir>/<File>.ttf' (relative to fonts/) */
export const FONT_METRICS: Record<string, FontMetrics> = {
${body}
}
`
)
console.log(`hash-fonts: wrote ${entries.length} entries to src/font-metrics.ts`)
